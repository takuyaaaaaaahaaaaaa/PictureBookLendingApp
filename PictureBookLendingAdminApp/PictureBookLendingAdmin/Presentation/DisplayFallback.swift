/// 参照先が見つからないときの表示用の既定値
///
/// 削除された図書・利用者・組を指す記録（貸出記録など）は残るため、
/// 参照を解決できない場面でも画面が無題にならないようにします。
/// 同じ事象を別の言葉で説明すると混乱を招くため、文言はここに集約します。
enum DisplayFallback {
    /// 図書を解決できない場合のタイトル表示
    static let bookTitle = "不明な図書"
    /// 利用者を解決できない場合の名前表示
    static let userName = "不明な利用者"
    /// 組を解決できない場合の名前表示
    static let classGroupName = "不明な組"
}
